package io.github.arcadiumclient.runtime.mixin.client;

import io.github.arcadiumclient.runtime.client.colorsaturation.CategoryColorRenderer;
import net.minecraft.client.render.world.WorldRenderer;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(WorldRenderer.class)
public abstract class CategoryColorWorldMixin {
    @Inject(method = "renderEntities", at = @At(value = "INVOKE_STRING",
            target = "Lnet/minecraft/util/profiler/Profiler;swap(Ljava/lang/String;)V", args = "ldc=blockentities"))
    private void arcadium$blockEntityColors(CallbackInfo callback) { CategoryColorRenderer.beginLayer(CategoryColorRenderer.WORLD); }
}
