package io.github.arcadiumclient.modern.mixin;

import io.github.arcadiumclient.modern.client.features.NoRender;
import net.minecraft.client.renderer.block.BlockRenderDispatcher;
import net.minecraft.client.renderer.block.model.BlockModelPart;
import net.minecraft.core.BlockPos;
import net.minecraft.world.level.BlockAndTintGetter;
import net.minecraft.world.level.block.state.BlockState;
import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.blaze3d.vertex.VertexConsumer;
import java.util.List;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(BlockRenderDispatcher.class)
public abstract class NoRenderBlocksMixin {
    @Inject(method = "renderBatched", at = @At("HEAD"), cancellable = true)
    private void arcadium$block(BlockState state, BlockPos position, BlockAndTintGetter level, PoseStack pose, VertexConsumer consumer, boolean cull, List<BlockModelPart> parts, CallbackInfo ci) { if (NoRender.block(state)) ci.cancel(); }
}
