package io.github.arcadiumclient.modern.mixin;

import io.github.arcadiumclient.modern.client.features.NoRender;
import io.github.arcadiumclient.modern.client.features.NoRenderPolicy.Effect;
import net.minecraft.client.renderer.WeatherEffectRenderer;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(WeatherEffectRenderer.class)
public abstract class NoRenderWeatherMixin {
    @Inject(method = {"render", "tickRainParticles"}, at = @At("HEAD"), cancellable = true)
    private void arcadium$render(CallbackInfo ci) { if (NoRender.effect(Effect.WEATHER)) ci.cancel(); }
}
